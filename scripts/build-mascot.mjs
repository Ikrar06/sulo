#!/usr/bin/env node
// Builds static mascot SVGs from assets/brand/mascot/mascot-base.svg and the
// eyes-*.svg files. No dependencies.
//
// Usage: node scripts/build-mascot.mjs
//
// Elements in mascot-base.svg are found by layer id (frame 510x540):
//   flame-back, flame   the two flame paths (gradient fills)
//   face-cut            face already clipped by the flame silhouette (static use)
//   face                full face oval (animation only, not used here)
//   eyes > eye-left, eye-right   default eyes
//   defs: face-clip     flame silhouette clipPath (animation only, not used here)
// The script fails loudly if an id is missing.
//
// Output (frame 510x512, the flame's own bounds): flame + face-cut + eyes
// clipped to the face shape. Layer ids are removed and gradient ids are
// prefixed per state, so several mascots can share one page without
// duplicate ids.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MASCOT_DIR = join(ROOT, 'assets/brand/mascot');
const OUT_DIR = join(MASCOT_DIR, 'static');
const FACE_FILL = '#0B0B10';

/** state name -> eyes file */
const STATES = {
  idle: 'eyes-open',
  sleepy: 'eyes-sleepy',
  happy: 'eyes-happy',
  wide: 'eyes-wide',
  dizzy: 'eyes-spiral',
  celebrate: 'eyes-star',
};

function fail(message) {
  console.error(`build-mascot: ${message}`);
  process.exit(1);
}

function innerOf(svg, file) {
  const match = /<svg\b[^>]*>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if (!match) fail(`${file}: bukan berkas SVG yang dikenali`);
  return match[1];
}

function elementById(svg, id, file) {
  const match = new RegExp(`<(path|ellipse|rect)\\b[^>]*\\bid="${id}"[^>]*/>`).exec(svg);
  if (!match) fail(`${file}: elemen dengan id "${id}" tidak ditemukan`);
  return match[0];
}

function stripId(element) {
  return element.replace(/\sid="[^"]*"/, '');
}

function parseBase() {
  const file = 'mascot-base.svg';
  const svg = readFileSync(join(MASCOT_DIR, file), 'utf8');
  if (!/viewBox="0 0 510 540"/.test(svg)) fail(`${file}: frame berubah (diharapkan viewBox 0 0 510 540)`);

  const flameBack = elementById(svg, 'flame-back', file);
  const flame = elementById(svg, 'flame', file);
  const faceCut = elementById(svg, 'face-cut', file);
  const faceOval = elementById(svg, 'face', file);
  elementById(svg, 'eye-left', file);
  elementById(svg, 'eye-right', file);

  if (!flameBack.includes('url(#') || !flame.includes('url(#')) fail(`${file}: flame-back dan flame harus bergradasi`);
  if (!faceCut.includes(`fill="${FACE_FILL}"`)) fail(`${file}: face-cut harus berwarna ${FACE_FILL}`);
  const faceD = /\sd="([^"]+)"/.exec(faceCut)?.[1];
  if (!faceD) fail(`${file}: face-cut tidak punya atribut d`);

  const gradientIds = [flameBack, flame].map((el) => /url\(#([^)]+)\)/.exec(el)[1]);
  const gradients = gradientIds.map((id) => {
    const g = new RegExp(`<linearGradient\\b[^>]*\\bid="${id}"[\\s\\S]*?</linearGradient>`).exec(svg)?.[0];
    if (!g) fail(`${file}: gradasi ${id} tidak ditemukan`);
    return g;
  });

  const oval = Object.fromEntries(['cx', 'cy', 'rx', 'ry'].map((k) => [k, Number(new RegExp(`\\s${k}="([^"]+)"`).exec(faceOval)?.[1])]));
  if (Object.values(oval).some((v) => !Number.isFinite(v))) fail(`${file}: face harus <ellipse> dengan cx, cy, rx, ry`);
  return { flame: [stripId(flameBack), stripId(flame)], face: stripId(faceCut), faceD, faceOval: oval, gradients };
}

function readEyes(name) {
  const file = `${name}.svg`;
  const svg = readFileSync(join(MASCOT_DIR, file), 'utf8');
  if (!/viewBox="0 0 510 512"/.test(svg)) fail(`${file}: frame berubah (diharapkan viewBox 0 0 510 512)`);
  const shapes = innerOf(svg, file).trim();
  if (!shapes) fail(`${file}: kosong`);
  if (/<(defs|g|use|image|mask|clipPath)\b/.test(shapes)) fail(`${file}: hanya bentuk sederhana yang didukung`);
  return shapes;
}

/** Gradient ids get a per-state prefix so several mascots can share one page. */
function namespaced(base, state) {
  const ids = base.gradients.map((g) => /id="([^"]+)"/.exec(g)[1]);
  const rename = (text) =>
    ids.reduce((out, id, i) => out.replaceAll(`"${id}"`, `"sulo-${state}-flame-${i}"`).replaceAll(`#${id})`, `#sulo-${state}-flame-${i})`), text);
  return {
    flame: base.flame.map(rename),
    gradients: base.gradients.map(rename),
  };
}

function compose(base, state, eyesFile) {
  const { flame, gradients } = namespaced(base, state);
  const clipId = `sulo-${state}-face`;
  const eyes = readEyes(eyesFile)
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => `    ${line}`)
    .join('\n');
  return `<svg width="510" height="512" viewBox="0 0 510 512" fill="none" xmlns="http://www.w3.org/2000/svg">
  <title>Sulo, maskot (${state})</title>
  <!-- Generated by scripts/build-mascot.mjs from mascot-base.svg + ${eyesFile}.svg. Do not edit by hand. -->
  ${flame.join('\n  ')}
  ${base.face}
  <g clip-path="url(#${clipId})">
${eyes}
  </g>
  <defs>
    <clipPath id="${clipId}">
      <path d="${base.faceD}"/>
    </clipPath>
    ${gradients.map((g) => g.replace(/\n/g, '\n    ')).join('\n    ')}
  </defs>
</svg>
`;
}

function previewHtml(names) {
  const cells = () =>
    names
      .map((n) => `<figure><img src="mascot-${n}.svg" alt="${n}" width="160" height="160"><figcaption>${n}</figcaption></figure>`)
      .join('\n      ');
  return `<!doctype html>
<html lang="id">
<head>
  <meta charset="utf-8">
  <title>Pratinjau maskot statis Sulo</title>
  <!-- Generated by scripts/build-mascot.mjs. Open this file directly in a browser. -->
  <style>
    body { margin: 0; font: 13px system-ui, sans-serif; }
    section { display: flex; flex-wrap: wrap; gap: 24px; padding: 24px; }
    figure { margin: 0; text-align: center; }
    img { display: block; object-fit: contain; }
    .dark { background: #0b0b0e; color: #f2f2f5; }
    .light { background: #fafafb; color: #111114; }
    .small img { width: 32px; height: 32px; }
  </style>
</head>
<body>
  <section class="dark">
      ${cells()}
  </section>
  <section class="light">
      ${cells()}
  </section>
  <section class="dark small">
      ${cells()}
  </section>
</body>
</html>
`;
}

/** Shapes for the animated React mascot (components/mascot), from the same sources. */
function shapesModule(base) {
  const attr = (el, name) => new RegExp(`\\s${name}="([^"]*)"`).exec(el)?.[1] ?? '';
  const gradient = (g) => ({
    x1: Number(attr(g, 'x1')),
    y1: Number(attr(g, 'y1')),
    x2: Number(attr(g, 'x2')),
    y2: Number(attr(g, 'y2')),
    stops: [...g.matchAll(/<stop\b[^>]*>/g)].map(([stop]) => ({
      offset: Number(attr(stop, 'offset') || 0),
      color: attr(stop, 'stop-color'),
    })),
  });
  const eyes = Object.fromEntries(
    Object.values(STATES).map((file) => [file.replace('eyes-', ''), readEyes(file).replace(/\s*\n\s*/g, '')]),
  );
  eyes.closed = readEyes('eyes-closed').replace(/\s*\n\s*/g, '');
  const data = {
    viewBox: '0 0 510 512',
    flame: base.flame.map((el) => attr(el, 'd')),
    gradients: base.gradients.map(gradient),
    face: base.faceD,
    /** Full face oval for the animated mascot, clipped by the flame silhouette. */
    faceOval: base.faceOval,
    eyes,
  };
  return `// Generated by scripts/build-mascot.mjs from assets/brand/mascot. Do not edit by hand.\n\nexport const MASCOT_SHAPES = ${JSON.stringify(data, null, 2)} as const;\n\nexport type EyesKey = keyof typeof MASCOT_SHAPES.eyes;\n`;
}

const base = parseBase();
mkdirSync(OUT_DIR, { recursive: true });
mkdirSync(join(ROOT, 'components/mascot'), { recursive: true });
writeFileSync(join(ROOT, 'components/mascot/shapes.generated.ts'), shapesModule(base));
for (const [state, eyesFile] of Object.entries(STATES)) {
  writeFileSync(join(OUT_DIR, `mascot-${state}.svg`), compose(base, state, eyesFile));
}
writeFileSync(join(OUT_DIR, 'preview.html'), previewHtml(Object.keys(STATES)));
console.log(`Ditulis ${Object.keys(STATES).length} maskot statis dan preview.html ke ${OUT_DIR}`);
