#!/usr/bin/env node
// Builds static mascot SVGs from assets/brand/mascot/mascot-base.svg and the
// eyes-*.svg files. No dependencies.
//
// Usage: node scripts/build-mascot.mjs
//
// mascot-base.svg has no layer ids yet, so elements are recognized by
// order and shape. The script fails loudly if that structure changes.
// Expected base structure (frame 510x540):
//   path #1, path #2   flame (gradient fills)
//   path #3            face already clipped by the flame silhouette
//   ellipse            full face oval (for animation; not used here)
//   rect, rect         default eyes
//   defs               two linearGradients
//
// Output (frame 510x512, the flame's own bounds):
//   flame + flattened face + eyes clipped to the face shape.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MASCOT_DIR = join(ROOT, 'assets/brand/mascot');
const OUT_DIR = join(MASCOT_DIR, 'static');
const FACE_FILL = '#0B0B10';

/** state name -> eyes file */
const STATES = {
  idle: 'eyes-open',
  sleepy: 'eyes-sleepy',
  happy: 'eyes-happy',
  wide: 'eyes-wide',
  dizzy: 'eyes-dizzy',
  celebrate: 'eyes-star',
};

function fail(message) {
  console.error(`build-mascot: ${message}`);
  process.exit(1);
}

function innerOf(svg, file) {
  const match = /<svg\b[^>]*>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if (!match) fail(`${file}: bukan berkas SVG yang dikenali`);
  return match[1];
}

function parseBase() {
  const file = 'mascot-base.svg';
  const svg = readFileSync(join(MASCOT_DIR, file), 'utf8');
  if (!/viewBox="0 0 510 540"/.test(svg)) fail(`${file}: frame berubah (diharapkan viewBox 0 0 510 540)`);
  const inner = innerOf(svg, file);

  const paths = inner.match(/<path\b[^>]*\/>/g) ?? [];
  const ellipses = inner.match(/<ellipse\b[^>]*\/>/g) ?? [];
  const rects = inner.match(/<rect\b[^>]*\/>/g) ?? [];
  const defs = /<defs>[\s\S]*<\/defs>/.exec(inner)?.[0];
  const gradients = defs?.match(/<linearGradient\b[\s\S]*?<\/linearGradient>/g) ?? [];

  if (paths.length !== 3 || ellipses.length !== 1 || rects.length !== 2 || gradients.length !== 2) {
    fail(
      `${file}: struktur berubah (path ${paths.length}/3, ellipse ${ellipses.length}/1, rect ${rects.length}/2, gradient ${gradients.length}/2). ` +
        'Perbarui skrip ini, atau pakai id layer setelah aset diekspor ulang.',
    );
  }
  const [flameA, flameB, face] = paths;
  if (!flameA.includes('url(#') || !flameB.includes('url(#')) fail(`${file}: dua path pertama harus api bergradasi`);
  if (!face.includes(`fill="${FACE_FILL}"`)) fail(`${file}: path ketiga harus wajah berwarna ${FACE_FILL}`);
  const faceD = /\sd="([^"]+)"/.exec(face)?.[1];
  if (!faceD) fail(`${file}: path wajah tidak punya atribut d`);

  return { flame: [flameA, flameB], face, faceD, gradients };
}

function readEyes(name) {
  const file = `${name}.svg`;
  const svg = readFileSync(join(MASCOT_DIR, file), 'utf8');
  if (!/viewBox="0 0 510 512"/.test(svg)) fail(`${file}: frame berubah (diharapkan viewBox 0 0 510 512)`);
  const shapes = innerOf(svg, file).trim();
  if (!shapes) fail(`${file}: kosong`);
  if (/<(defs|g|use|image|mask|clipPath)\b/.test(shapes)) fail(`${file}: hanya bentuk sederhana yang didukung`);
  return shapes;
}

/** Gradient ids get a per-state prefix so several mascots can share one page. */
function namespaced(base, state) {
  const ids = base.gradients.map((g) => /id="([^"]+)"/.exec(g)[1]);
  const rename = (text) =>
    ids.reduce((out, id, i) => out.replaceAll(`"${id}"`, `"sulo-${state}-flame-${i}"`).replaceAll(`#${id})`, `#sulo-${state}-flame-${i})`), text);
  return {
    flame: base.flame.map(rename),
    gradients: base.gradients.map(rename),
  };
}

function compose(base, state, eyesFile) {
  const { flame, gradients } = namespaced(base, state);
  const clipId = `sulo-${state}-face`;
  const eyes = readEyes(eyesFile)
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => `    ${line}`)
    .join('\n');
  return `<svg width="510" height="512" viewBox="0 0 510 512" fill="none" xmlns="http://www.w3.org/2000/svg">
  <title>Sulo, maskot (${state})</title>
  <!-- Generated by scripts/build-mascot.mjs from mascot-base.svg + ${eyesFile}.svg. Do not edit by hand. -->
  ${flame.join('\n  ')}
  ${base.face}
  <g clip-path="url(#${clipId})">
${eyes}
  </g>
  <defs>
    <clipPath id="${clipId}">
      <path d="${base.faceD}"/>
    </clipPath>
    ${gradients.map((g) => g.replace(/\n/g, '\n    ')).join('\n    ')}
  </defs>
</svg>
`;
}

function previewHtml(names) {
  const cells = () =>
    names
      .map((n) => `<figure><img src="mascot-${n}.svg" alt="${n}" width="160" height="160"><figcaption>${n}</figcaption></figure>`)
      .join('\n      ');
  return `<!doctype html>
<html lang="id">
<head>
  <meta charset="utf-8">
  <title>Pratinjau maskot statis Sulo</title>
  <!-- Generated by scripts/build-mascot.mjs. Open this file directly in a browser. -->
  <style>
    body { margin: 0; font: 13px system-ui, sans-serif; }
    section { display: flex; flex-wrap: wrap; gap: 24px; padding: 24px; }
    figure { margin: 0; text-align: center; }
    img { display: block; object-fit: contain; }
    .dark { background: #0b0b0e; color: #f2f2f5; }
    .light { background: #fafafb; color: #111114; }
    .small img { width: 32px; height: 32px; }
  </style>
</head>
<body>
  <section class="dark">
      ${cells()}
  </section>
  <section class="light">
      ${cells()}
  </section>
  <section class="dark small">
      ${cells()}
  </section>
</body>
</html>
`;
}

const base = parseBase();
mkdirSync(OUT_DIR, { recursive: true });
for (const [state, eyesFile] of Object.entries(STATES)) {
  writeFileSync(join(OUT_DIR, `mascot-${state}.svg`), compose(base, state, eyesFile));
}
writeFileSync(join(OUT_DIR, 'preview.html'), previewHtml(Object.keys(STATES)));
console.log(`Ditulis ${Object.keys(STATES).length} maskot statis dan preview.html ke ${OUT_DIR}`);
